import { mkdir, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const run = promisify(execFile);

const endpoint = new URL("https://vip.stock.finance.sina.com.cn/quotes_service/api/json_v2.php/Market_Center.getHQNodeData");
const baseParams = { num: "100", sort: "symbol", asc: "1", node: "hs_a", symbol: "", _s_r_a: "page" };

async function loadPage(page) {
  endpoint.search = new URLSearchParams({ ...baseParams, pn: String(page) }).toString();
  endpoint.searchParams.set("page", String(page));
  endpoint.searchParams.delete("pn");
  const { stdout } = await run("curl", ["-4", "-L", "--fail", "--max-time", "30", "--silent", "--show-error", "--compressed", "-A", "Mozilla/5.0", endpoint.href], { maxBuffer: 10 * 1024 * 1024 });
  return JSON.parse(stdout);
}

const countUrl = "https://vip.stock.finance.sina.com.cn/quotes_service/api/json_v2.php/Market_Center.getHQNodeStockCount?node=hs_a";
const { stdout: countText } = await run("curl", ["-4", "-L", "--fail", "--max-time", "30", "--silent", "--show-error", "--compressed", "-A", "Mozilla/5.0", countUrl]);
const total = Number(JSON.parse(countText));
const first = await loadPage(1);
const pageCount = Math.ceil(total / 100);
const remaining = [];
for (let page = 2; page <= pageCount; page += 8) {
  remaining.push(...await Promise.all(Array.from({ length: Math.min(8, pageCount - page + 1) }, (_, index) => loadPage(page + index))));
}
const stocks = [first, ...remaining].flatMap((page) => Array.isArray(page) ? page : []);
if (!Array.isArray(stocks) || stocks.length < 5000) throw new Error(`Expected at least 5000 A-shares, received ${stocks?.length ?? 0}`);

const entries = stocks
  .filter((stock) => /^(sh|sz|bj)\d{6}$/.test(stock.symbol) && typeof stock.name === "string")
  .map((stock) => ({
    code: stock.code,
    name: stock.name,
    exchange: stock.symbol.slice(0, 2),
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

const source = `// Generated by scripts/update-cn-universe.mjs.\nexport type CnStockEntry = { code: string; name: string; exchange: "sh" | "sz" | "bj" };\nexport const CN_STOCK_UNIVERSE = JSON.parse(${JSON.stringify(JSON.stringify(entries))}) as CnStockEntry[];\n`;
await mkdir(new URL("../app/", import.meta.url), { recursive: true });
await writeFile(new URL("../app/cn-stock-universe.ts", import.meta.url), source);
console.log(`Wrote ${entries.length} A-share listings.`);
