const replacements = Object.entries(GERMAN).sort(
  ([left], [right]) => right.length - left.length,
);

export function translateEnglishToGerman(text: string) {
  let translated = text;
  for (const [source, target] of replacements) {
    if (source.length <= 3) {
      if (translated.trim() === source) translated = translated.replace(source, target);
    } else if (translated.includes(source)) {
      translated = translated.replaceAll(source, target);
    }
  }
  return translated
    .replace(/\bSTEP\s+(\d+)\/(\d+)/gu, "SCHRITT $1/$2")
    .replace(/\bDecision\s+(\d+)\/(\d+)/gu, "Entscheidung $1/$2")
    .replace(/\bDecision\s+(\d+)/gu, "Entscheidung $1")
    .replace(/\bStage\s+(\d+)\s+of\s+(\d+)/gu, "Stufe $1 von $2")
    .replace(/\bMarket\s+(\d+)\/(\d+)/gu, "Markt $1/$2")
    .replace(/(\d+(?:[.,]\d+)?)\s+trading days/gu, "$1 Handelstage")
    .replace(/(\d+(?:[.,]\d+)?)\s+days/gu, "$1 Tage")
    .replace(/(\d+(?:[.,]\d+)?)\s+shares/gu, "$1 Aktien")
    .replace(/(\d+(?:[.,]\d+)?)\s+candles/gu, "$1 Kerzen")
    .replace(/(\d+(?:[.,]\d+)?)\s+lessons/gu, "$1 Lektionen")
    .replace(/(\d+(?:[.,]\d+)?)\s+decisions left/gu, "Noch $1 Entscheidungen");
}
