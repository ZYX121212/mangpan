const replacements = Object.entries(FRENCH).sort(
  ([left], [right]) => right.length - left.length,
);

export function translateEnglishToFrench(text: string) {
  let translated = text;
  for (const [source, target] of replacements) {
    if (source.length <= 3) {
      if (translated.trim() === source)
        translated = translated.replace(source, target);
    } else if (translated.includes(source)) {
      translated = translated.replaceAll(source, target);
    }
  }
  return translated
    .replace(/\bSTEP\s+(\d+)\/(\d+)/gu, "ÉTAPE $1/$2")
    .replace(/\bDecision\s+(\d+)\/(\d+)/gu, "Décision $1/$2")
    .replace(/\bDecision\s+(\d+)/gu, "Décision $1")
    .replace(/\bStage\s+(\d+)\s+of\s+(\d+)/gu, "Étape $1 sur $2")
    .replace(/\bMarket\s+(\d+)\/(\d+)/gu, "Marché $1/$2")
    .replace(/(\d+(?:[.,]\d+)?)\s+trading days/gu, "$1 jours de bourse")
    .replace(/(\d+(?:[.,]\d+)?)\s+days/gu, "$1 jours")
    .replace(/(\d+(?:[.,]\d+)?)\s+shares/gu, "$1 actions")
    .replace(/(\d+(?:[.,]\d+)?)\s+candles/gu, "$1 bougies")
    .replace(/(\d+(?:[.,]\d+)?)\s+lessons/gu, "$1 leçons")
    .replace(/(\d+(?:[.,]\d+)?)\s+decisions left/gu, "$1 décisions restantes");
}
