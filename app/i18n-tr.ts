export function translateEnglishToTurkish(text: string) {
  let translated = text;
  for (const [source, target] of Object.entries(TURKISH).sort(
    ([left], [right]) => right.length - left.length,
  )) {
    translated = translated.replaceAll(source, target);
  }
  return translated;
}
